-- ---------------------------------------------------------------------
-- DIM_TIEMPO · clave inteligente AAAAMMDD; la puebla el ETL
-- ---------------------------------------------------------------------
CREATE TABLE DIM_TIEMPO (
  sk_tiempo      NUMBER(8)     NOT NULL,
  fecha          DATE,
  anio           NUMBER(4),
  trimestre      NUMBER(1),
  mes            NUMBER(2),
  nombre_mes     VARCHAR2(15),
  anio_mes       VARCHAR2(7),          -- '2017-11' para ordenar en Excel
  dia            NUMBER(2),
  dia_semana     NUMBER(1),            -- 1 = lunes ... 7 = domingo
  nombre_dia     VARCHAR2(15),
  es_fin_semana  VARCHAR2(3 CHAR),     -- 'Sí' / 'No'
  CONSTRAINT pk_dim_tiempo PRIMARY KEY (sk_tiempo),
  CONSTRAINT uk_dim_tiempo_fecha UNIQUE (fecha)
);

-- ---------------------------------------------------------------------
-- DIM_CLIENTE · un registro por cliente real (customer_unique_id)
-- ---------------------------------------------------------------------
CREATE TABLE DIM_CLIENTE (
  sk_cliente          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  customer_unique_id  VARCHAR2(32)  NOT NULL,
  codigo_postal       VARCHAR2(5),
  ciudad              VARCHAR2(100),
  estado              VARCHAR2(2),
  region              VARCHAR2(20),
  latitud             NUMBER(10,6),
  longitud            NUMBER(10,6),
  CONSTRAINT pk_dim_cliente PRIMARY KEY (sk_cliente),
  CONSTRAINT uk_dim_cliente_nk UNIQUE (customer_unique_id)
);

-- ---------------------------------------------------------------------
-- DIM_VENDEDOR
-- ---------------------------------------------------------------------
CREATE TABLE DIM_VENDEDOR (
  sk_vendedor    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  seller_id      VARCHAR2(32)  NOT NULL,
  codigo_postal  VARCHAR2(5),
  ciudad         VARCHAR2(100),
  estado         VARCHAR2(2),
  region         VARCHAR2(20),
  latitud        NUMBER(10,6),
  longitud       NUMBER(10,6),
  CONSTRAINT pk_dim_vendedor PRIMARY KEY (sk_vendedor),
  CONSTRAINT uk_dim_vendedor_nk UNIQUE (seller_id)
);

-- ---------------------------------------------------------------------
-- DIM_PRODUCTO
-- ---------------------------------------------------------------------
CREATE TABLE DIM_PRODUCTO (
  sk_producto     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  product_id      VARCHAR2(32)  NOT NULL,
  categoria_pt    VARCHAR2(80),
  categoria_en    VARCHAR2(80),
  peso_g          NUMBER(8),
  largo_cm        NUMBER(6),
  alto_cm         NUMBER(6),
  ancho_cm        NUMBER(6),
  volumen_cm3     NUMBER(12),
  rango_peso      VARCHAR2(20),
  cantidad_fotos  NUMBER(3),
  CONSTRAINT pk_dim_producto PRIMARY KEY (sk_producto),
  CONSTRAINT uk_dim_producto_nk UNIQUE (product_id)
);

-- ---------------------------------------------------------------------
-- DIM_ESTADO_ORDEN
-- ---------------------------------------------------------------------
CREATE TABLE DIM_ESTADO_ORDEN (
  sk_estado_orden  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  estado_orden     VARCHAR2(20)  NOT NULL,
  estado_orden_es  VARCHAR2(30),
  es_completada    VARCHAR2(3 CHAR),   -- 'Sí' solo para delivered
  CONSTRAINT pk_dim_estado_orden PRIMARY KEY (sk_estado_orden),
  CONSTRAINT uk_dim_estado_orden_nk UNIQUE (estado_orden)
);

-- ---------------------------------------------------------------------
-- DIM_TIPO_PAGO
-- ---------------------------------------------------------------------
CREATE TABLE DIM_TIPO_PAGO (
  sk_tipo_pago  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1),
  tipo_pago     VARCHAR2(20)  NOT NULL,
  tipo_pago_es  VARCHAR2(30),
  CONSTRAINT pk_dim_tipo_pago PRIMARY KEY (sk_tipo_pago),
  CONSTRAINT uk_dim_tipo_pago_nk UNIQUE (tipo_pago)
);

