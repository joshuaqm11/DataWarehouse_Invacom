-- EJECUTAR: en SQL Developer con la conexión DW_INVACOM, como script (F5)
-- Requiere Oracle 12c o superior (columnas IDENTITY).
-- Orden de ejecución: 01_dimensiones.sql -> 02_hechos.sql
-- Para rehacer todo desde cero: 99_eliminar_dw.sql y volver a empezar.
